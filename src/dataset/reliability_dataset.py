"""
Reliability training dataset for the DFG project.

Builds 51-D frame features:
    IMU    21-D
    GPS    12-D
    LiDAR  10-D placeholder
    Camera  8-D placeholder

and aligns them with the oracle GPS reliability labels generated by
run_dynamic_covariance_fg.py.

The feature at aligned step k corresponds to raw KITTI frame:
    raw_frame = k + feature_window - 1
"""

from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Dict, Optional, Tuple

import numpy as np
import torch
from torch.utils.data import Dataset


PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))


from src.loader.imu_loader import IMULoader

try:
    from src.feature.imu_feature import IMUFeatureExtractor
    from src.feature.gps_feature import GPSFeatureExtractor
    from src.feature.fusion_feature import FusionFeatureExtractor
except ModuleNotFoundError:
    from src.features.imu_feature import IMUFeatureExtractor
    from src.features.gps_feature import GPSFeatureExtractor
    from src.features.fusion_feature import FusionFeatureExtractor


DEFAULT_DATASET = (
    PROJECT_ROOT
    / "dataset"
    / "kitti"
    / "2011_10_03"
    / "2011_10_03_drive_0027_sync"
)

DEFAULT_GPS_PATH = (
    PROJECT_ROOT
    / "results"
    / "gps_degradation"
    / "gps_corrupted.txt"
)

DEFAULT_LABEL_PATH = (
    PROJECT_ROOT
    / "results"
    / "dynamic_covariance_fg"
    / "reliability.txt"
)


def load_raw_imu(sequence_path: Path) -> np.ndarray:
    """
    Return Nx6:
        ax ay az gx gy gz
    """
    loader = IMULoader(sequence_path)

    rows = []
    for i in range(len(loader)):
        item = loader[i]

        acc = np.asarray(
            item["acceleration"],
            dtype=np.float64,
        )

        gyro = np.asarray(
            item["angular_velocity"],
            dtype=np.float64,
        )

        rows.append(
            np.concatenate(
                [acc, gyro],
                axis=0,
            )
        )

    return np.asarray(
        rows,
        dtype=np.float64,
    )


def build_frame_features(
    sequence_path: Path = DEFAULT_DATASET,
    gps_path: Path = DEFAULT_GPS_PATH,
    label_path: Path = DEFAULT_LABEL_PATH,
    feature_window: int = 10,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Build aligned frame-level features and labels.

    Returns
    -------
    features:
        Mx51 float32

    labels:
        M float32

    raw_frame_ids:
        M int64
        Original KITTI frame index associated with each feature row.
    """
    sequence_path = Path(sequence_path)
    gps_path = Path(gps_path)
    label_path = Path(label_path)

    if not sequence_path.exists():
        raise FileNotFoundError(
            f"Dataset not found: {sequence_path}"
        )

    if not gps_path.exists():
        raise FileNotFoundError(
            f"GPS file not found: {gps_path}"
        )

    if not label_path.exists():
        raise FileNotFoundError(
            f"Reliability label not found: {label_path}"
        )

    imu_raw = load_raw_imu(
        sequence_path
    )

    gps_raw = np.loadtxt(
        gps_path,
        dtype=np.float64,
    )

    labels_raw = np.loadtxt(
        label_path,
        dtype=np.float64,
    )

    gps_raw = np.asarray(
        gps_raw,
        dtype=np.float64,
    ).reshape(-1, 3)

    labels_raw = np.asarray(
        labels_raw,
        dtype=np.float64,
    ).reshape(-1)

    n = len(imu_raw)

    if len(gps_raw) != n:
        raise RuntimeError(
            f"GPS frames {len(gps_raw)} != IMU frames {n}"
        )

    if len(labels_raw) != n:
        raise RuntimeError(
            f"Reliability labels {len(labels_raw)} != IMU frames {n}"
        )

    if feature_window < 1:
        raise ValueError(
            "feature_window must be >= 1"
        )

    if feature_window > n:
        raise ValueError(
            f"feature_window {feature_window} > frame count {n}"
        )

    imu_extractor = IMUFeatureExtractor(
        window_size=feature_window,
        dt=0.1,
    )

    gps_extractor = GPSFeatureExtractor()

    fusion_extractor = FusionFeatureExtractor(
        normalize=False
    )

    lidar_placeholder = np.zeros(
        10,
        dtype=np.float64,
    )

    camera_placeholder = np.zeros(
        8,
        dtype=np.float64,
    )

    features = []
    frame_ids = []

    for end in range(
        feature_window - 1,
        n,
    ):
        start = (
            end
            -
            feature_window
            +
            1
        )

        imu_window = imu_raw[
            start:end + 1
        ]

        gps_window = gps_raw[
            start:end + 1
        ]

        imu_feature = (
            imu_extractor.extract(
                imu_window
            )
        )

        gps_feature = (
            gps_extractor.extract(
                gps_window
            )
        )

        fused = (
            fusion_extractor.extract(
                imu_feature,
                gps_feature,
                lidar_placeholder,
                camera_placeholder,
            )
        )

        if fused.shape != (51,):
            raise RuntimeError(
                f"Fusion feature must be 51-D, got {fused.shape}"
            )

        features.append(
            fused
        )

        frame_ids.append(
            end
        )

    features = np.asarray(
        features,
        dtype=np.float32,
    )

    frame_ids = np.asarray(
        frame_ids,
        dtype=np.int64,
    )

    labels = labels_raw[
        frame_ids
    ].astype(
        np.float32
    )

    features = np.nan_to_num(
        features,
        nan=0.0,
        posinf=0.0,
        neginf=0.0,
    )

    labels = np.clip(
        np.nan_to_num(
            labels,
            nan=0.0,
            posinf=1.0,
            neginf=0.0,
        ),
        0.0,
        1.0,
    ).astype(
        np.float32
    )

    return (
        features,
        labels,
        frame_ids,
    )


def compute_normalization(
    features: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Feature-wise z-score statistics.
    """
    features = np.asarray(
        features,
        dtype=np.float64,
    )

    mean = np.mean(
        features,
        axis=0,
    )

    std = np.std(
        features,
        axis=0,
    )

    std[
        std < 1e-8
    ] = 1.0

    return (
        mean.astype(
            np.float32
        ),
        std.astype(
            np.float32
        ),
    )


def normalize_features(
    features: np.ndarray,
    mean: np.ndarray,
    std: np.ndarray,
) -> np.ndarray:
    return (
        (
            features
            -
            mean
        )
        /
        std
    ).astype(
        np.float32
    )


class ReliabilitySequenceDataset(Dataset):
    """
    Sequence dataset.

    Each item:
        feature: T x 51
        label:   T
        frame_ids: T

    The label is GPS reliability in [0, 1].
    """

    def __init__(
        self,
        features: np.ndarray,
        labels: np.ndarray,
        frame_ids: np.ndarray,
        sequence_length: int = 64,
        stride: int = 8,
        allowed_window_indices: Optional[np.ndarray] = None,
    ):
        self.features = np.asarray(
            features,
            dtype=np.float32,
        )

        self.labels = np.asarray(
            labels,
            dtype=np.float32,
        ).reshape(-1)

        self.frame_ids = np.asarray(
            frame_ids,
            dtype=np.int64,
        ).reshape(-1)

        if len(self.features) != len(self.labels):
            raise ValueError(
                "features and labels length mismatch"
            )

        if len(self.features) != len(self.frame_ids):
            raise ValueError(
                "features and frame_ids length mismatch"
            )

        if self.features.ndim != 2:
            raise ValueError(
                "features must be NxD"
            )

        if self.features.shape[1] != 51:
            raise ValueError(
                f"feature dimension must be 51, got {self.features.shape[1]}"
            )

        self.sequence_length = int(
            sequence_length
        )

        self.stride = int(
            stride
        )

        if self.sequence_length < 1:
            raise ValueError(
                "sequence_length must be >= 1"
            )

        if self.stride < 1:
            raise ValueError(
                "stride must be >= 1"
            )

        max_start = (
            len(self.features)
            -
            self.sequence_length
        )

        if max_start < 0:
            raise ValueError(
                "sequence_length is larger than available features"
            )

        starts = np.arange(
            0,
            max_start + 1,
            self.stride,
            dtype=np.int64,
        )

        if allowed_window_indices is not None:
            allowed_window_indices = np.asarray(
                allowed_window_indices,
                dtype=np.int64,
            )

            starts = starts[
                allowed_window_indices
            ]

        self.starts = starts

    def __len__(self):
        return len(
            self.starts
        )

    def __getitem__(
        self,
        index,
    ):
        start = int(
            self.starts[index]
        )

        end = (
            start
            +
            self.sequence_length
        )

        x = self.features[
            start:end
        ]

        y = self.labels[
            start:end
        ]

        f = self.frame_ids[
            start:end
        ]

        return {
            "feature": torch.from_numpy(
                x
            ),
            "label": torch.from_numpy(
                y
            ),
            "frame_ids": torch.from_numpy(
                f
            ),
        }


def build_window_split_indices(
    total_feature_rows: int,
    sequence_length: int,
    stride: int,
    block_size: int = 256,
) -> Dict[str, np.ndarray]:
    """
    Block-based split to reduce direct overlap leakage.

    Window split is determined by the block containing the
    sequence's last aligned frame-row.

    block_id % 10:
        0 -> test
        1 -> validation
        2..9 -> train

    Returns indices into the common list of candidate window starts.
    """
    max_start = (
        total_feature_rows
        -
        sequence_length
    )

    starts = np.arange(
        0,
        max_start + 1,
        stride,
        dtype=np.int64,
    )

    ends = (
        starts
        +
        sequence_length
        -
        1
    )

    block_ids = (
        ends
        //
        block_size
    )

    mod = (
        block_ids
        %
        10
    )

    test_idx = np.where(
        mod == 0
    )[0]

    val_idx = np.where(
        mod == 1
    )[0]

    train_idx = np.where(
        mod >= 2
    )[0]

    return {
        "train": train_idx,
        "val": val_idx,
        "test": test_idx,
    }
