def set_seed(
    seed: int,
):
    random.seed(
        seed
    )

    np.random.seed(
        seed
    )

    torch.manual_seed(
        seed
    )

    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(
            seed
        )


def choose_device():
    if torch.cuda.is_available():
        return torch.device(
            "cuda"
        )

    return torch.device(
        "cpu"
    )


def metrics_from_arrays(
    pred: np.ndarray,
    target: np.ndarray,
):
    pred = np.asarray(
        pred,
        dtype=np.float64,
    ).reshape(-1)

    target = np.asarray(
        target,
        dtype=np.float64,
    ).reshape(-1)

    error = (
        pred
        -
        target
    )

    mae = float(
        np.mean(
            np.abs(
                error
            )
        )
    )

    rmse = float(
        np.sqrt(
            np.mean(
                error ** 2
            )
        )
    )

    if (
        np.std(pred) > 1e-12
        and
        np.std(target) > 1e-12
    ):
        corr = float(
            np.corrcoef(
                pred,
                target,
            )[0, 1]
        )
    else:
        corr = 0.0

    binary_pred = (
        pred >= 0.5
    )

    binary_target = (
        target >= 0.5
    )

    accuracy = float(
        np.mean(
            binary_pred
            ==
            binary_target
        )
    )

    return {
        "MAE": mae,
        "RMSE": rmse,
        "Correlation": corr,
        "BinaryAccuracy@0.5": accuracy,
    }


# ============================================================
# Epoch
# ============================================================

def run_epoch(
    model,
    loader,
    loss_fn,
    device,
    optimizer=None,
):
    training = (
        optimizer is not None
    )

    if training:
        model.train()
    else:
        model.eval()

    loss_sum = 0.0

    sample_count = 0

    predictions = []

    targets = []

    for batch in loader:
        feature = batch[
            "feature"
        ].to(
            device
        )

        label = batch[
            "label"
        ].to(
            device
        )

        if training:
            optimizer.zero_grad(
                set_to_none=True
            )

        with torch.set_grad_enabled(
            training
        ):
            output = model(
                feature
            )

            pred = output[
                "gps_reliability"
            ]

            loss = loss_fn(
                pred,
                label
            )

            if training:
                loss.backward()

                torch.nn.utils.clip_grad_norm_(
                    model.parameters(),
                    GRAD_CLIP,
                )

                optimizer.step()

        batch_size = int(
            feature.shape[0]
        )

        loss_sum += (
            float(
                loss.item()
            )
            *
            batch_size
        )

        sample_count += (
            batch_size
        )

        predictions.append(
            pred.detach()
            .cpu()
            .numpy()
            .reshape(-1)
        )

        targets.append(
            label.detach()
            .cpu()
            .numpy()
            .reshape(-1)
        )

    if sample_count == 0:
        raise RuntimeError(
            "Empty DataLoader"
        )

    pred_array = np.concatenate(
        predictions
    )

    target_array = np.concatenate(
        targets
    )

    metrics = metrics_from_arrays(
        pred_array,
        target_array,
    )

    metrics[
        "Loss"
    ] = (
        loss_sum
        /
        sample_count
    )

    return metrics


# ============================================================
# Full sequence prediction
# ============================================================

@torch.no_grad()
def predict_all_frames(
    model,
    normalized_features,
    raw_frame_ids,
    raw_frame_count,
    device,
):
    """
    Causal-style prediction.

    For each aligned feature row, construct a sequence ending at the
    current row and use only the final-step GPS reliability prediction.

    The earliest raw frames before FEATURE_WINDOW-1 are filled with
    the first available model prediction.
    """
    model.eval()

    features = torch.from_numpy(
        normalized_features.astype(
            np.float32
        )
    )

    aligned_count = len(
        normalized_features
    )

    sequence_list = []

    prediction_rows = []

    batch_limit = 128


    def flush_batch():
        if not sequence_list:
            return

        batch = torch.stack(
            sequence_list,
            dim=0,
        ).to(
            device
        )

        output = model(
            batch
        )

        pred = (
            output[
                "gps_reliability"
            ][
                :,
                -1
            ]
            .detach()
            .cpu()
            .numpy()
        )

        prediction_rows.extend(
            pred.tolist()
        )

        sequence_list.clear()


    for i in range(
        aligned_count
    ):
        start = max(
            0,
            i
            -
            SEQUENCE_LENGTH
            +
            1,
        )

        seq = features[
            start:i + 1
        ]

        if len(seq) < SEQUENCE_LENGTH:
            pad_count = (
                SEQUENCE_LENGTH
                -
                len(seq)
            )

            pad = (
                seq[0:1]
                .repeat(
                    pad_count,
                    1,
                )
            )

            seq = torch.cat(
                [
                    pad,
                    seq,
                ],
                dim=0,
            )

        sequence_list.append(
            seq
        )

        if len(sequence_list) >= batch_limit:
            flush_batch()

    flush_batch()

    aligned_prediction = np.asarray(
        prediction_rows,
        dtype=np.float64,
    )

    aligned_prediction = np.clip(
        aligned_prediction,
        0.0,
        1.0,
    )

    full_prediction = np.ones(
        raw_frame_count,
        dtype=np.float64,
    )

    if len(aligned_prediction) == 0:
        raise RuntimeError(
            "No predictions generated"
        )

    first_frame = int(
        raw_frame_ids[0]
    )

    full_prediction[
        :first_frame
    ] = aligned_prediction[0]

    full_prediction[
        raw_frame_ids
    ] = aligned_prediction

    return full_prediction


# ============================================================
# Main
# ============================================================

def main():
    set_seed(
        SEED
    )

    RESULT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    device = choose_device()

    print(
        "="
        *
        60
    )

    print(
        "Mamba GPS Reliability Training"
    )

    print(
        "="
        *
        60
    )

    print(
        "Device:",
        device
    )

    print(
        "Dataset:",
        DEFAULT_DATASET
    )

    print(
        "GPS:",
        DEFAULT_GPS_PATH
    )

    print(
        "Label:",
        DEFAULT_LABEL_PATH
    )

    print()

    # --------------------------------------------------------
    # Build frame features
    # --------------------------------------------------------

    print(
        "Building 51-D frame features..."
    )

    (
        features,
        labels,
        frame_ids,
    ) = build_frame_features(
        sequence_path=DEFAULT_DATASET,
        gps_path=DEFAULT_GPS_PATH,
        label_path=DEFAULT_LABEL_PATH,
        feature_window=FEATURE_WINDOW,
    )

    print(
        "Features:",
        features.shape
    )

    print(
        "Labels:",
        labels.shape
    )

    print(
        "Frame IDs:",
        frame_ids.shape
    )

    # --------------------------------------------------------
    # Split candidate windows
    # --------------------------------------------------------

    split = build_window_split_indices(
        total_feature_rows=len(
            features
        ),
        sequence_length=SEQUENCE_LENGTH,
        stride=SEQUENCE_STRIDE,
        block_size=SPLIT_BLOCK_SIZE,
    )

    # For feature normalization, collect feature rows used by
    # training windows only.

    all_starts = np.arange(
        0,
        len(features)
        -
        SEQUENCE_LENGTH
        +
        1,
        SEQUENCE_STRIDE,
        dtype=np.int64,
    )

    train_starts = all_starts[
        split["train"]
    ]

    train_row_mask = np.zeros(
        len(features),
        dtype=bool,
    )

    for start in train_starts:
        train_row_mask[
            start:
            start
            +
            SEQUENCE_LENGTH
        ] = True

    mean, std = compute_normalization(
        features[
            train_row_mask
        ]
    )

    normalized_features = normalize_features(
        features,
        mean,
        std,
    )

    np.savez(
        NORMALIZATION_PATH,
        mean=mean,
        std=std,
        feature_window=np.array(
            [FEATURE_WINDOW],
            dtype=np.int64,
        ),
        sequence_length=np.array(
            [SEQUENCE_LENGTH],
            dtype=np.int64,
        ),
    )

    # --------------------------------------------------------
    # Datasets
    # --------------------------------------------------------

    common_kwargs = dict(
        features=normalized_features,
        labels=labels,
        frame_ids=frame_ids,
        sequence_length=SEQUENCE_LENGTH,
        stride=SEQUENCE_STRIDE,
    )

    train_dataset = ReliabilitySequenceDataset(
        **common_kwargs,
        allowed_window_indices=split[
            "train"
        ],
    )

    val_dataset = ReliabilitySequenceDataset(
        **common_kwargs,
        allowed_window_indices=split[
            "val"
        ],
    )

    test_dataset = ReliabilitySequenceDataset(
        **common_kwargs,
        allowed_window_indices=split[
            "test"
        ],
    )

    print()

    print(
        "Train windows:",
        len(train_dataset)
    )

    print(
        "Validation windows:",
        len(val_dataset)
    )

    print(
        "Test windows:",
        len(test_dataset)
    )

    # --------------------------------------------------------
    # Loaders
    # --------------------------------------------------------

    pin_memory = (
        device.type
        ==
        "cuda"
    )

    train_loader = DataLoader(
        train_dataset,
        batch_size=BATCH_SIZE,
        shuffle=True,
        num_workers=NUM_WORKERS,
        pin_memory=pin_memory,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=BATCH_SIZE,
        shuffle=False,
        num_workers=NUM_WORKERS,
        pin_memory=pin_memory,
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=BATCH_SIZE,
        shuffle=False,
        num_workers=NUM_WORKERS,
        pin_memory=pin_memory,
    )

    # --------------------------------------------------------
    # Model
    # --------------------------------------------------------

    model = MambaReliabilityModel(
        input_dim=51,
        hidden_dim=128,
        state_dim=16,
        num_layers=2,
        head_hidden_dim=64,
        sensor_num=4,
        gps_channel=1,
    ).to(
        device
    )

    loss_fn = WeightedReliabilityMSE(
        low_reliability_weight=LOW_RELIABILITY_WEIGHT
    )

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=LEARNING_RATE,
        weight_decay=WEIGHT_DECAY,
    )

    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer,
        mode="min",
        factor=0.5,
        patience=3,
    )

    # --------------------------------------------------------
    # Training
    # --------------------------------------------------------

    history_rows = []

    best_val = math.inf

    best_epoch = -1

    no_improvement = 0

    print()

    print(
        "Training..."
    )

    print()

    for epoch in range(
        1,
        EPOCHS + 1,
    ):
        train_metrics = run_epoch(
            model,
            train_loader,
            loss_fn,
            device,
            optimizer=optimizer,
        )

        val_metrics = run_epoch(
            model,
            val_loader,
            loss_fn,
            device,
            optimizer=None,
        )

        scheduler.step(
            val_metrics[
                "Loss"
            ]
        )

        lr = float(
            optimizer.param_groups[
                0
            ][
                "lr"
            ]
        )

        history_rows.append(
            [
                epoch,
                train_metrics[
                    "Loss"
                ],
                train_metrics[
                    "MAE"
                ],
                train_metrics[
                    "RMSE"
                ],
                val_metrics[
                    "Loss"
                ],
                val_metrics[
                    "MAE"
                ],
                val_metrics[
                    "RMSE"
                ],
                val_metrics[
                    "Correlation"
                ],
                lr,
            ]
        )

        print(
            f"Epoch {epoch:03d} | "
            f"train loss {train_metrics['Loss']:.6f} | "
            f"val loss {val_metrics['Loss']:.6f} | "
            f"val MAE {val_metrics['MAE']:.6f} | "
            f"val RMSE {val_metrics['RMSE']:.6f} | "
            f"corr {val_metrics['Correlation']:.4f} | "
            f"lr {lr:.2e}"
        )

        current_val = float(
            val_metrics[
                "Loss"
            ]
        )

        if current_val < best_val:
            best_val = current_val

            best_epoch = epoch

            no_improvement = 0

            torch.save(
                {
                    "epoch": epoch,
                    "model_state_dict": model.state_dict(),
                    "optimizer_state_dict": optimizer.state_dict(),
                    "val_metrics": val_metrics,
                    "config": {
                        "feature_window": FEATURE_WINDOW,
                        "sequence_length": SEQUENCE_LENGTH,
                        "sequence_stride": SEQUENCE_STRIDE,
                        "input_dim": 51,
                        "hidden_dim": 128,
                        "state_dim": 16,
                        "num_layers": 2,
                        "gps_channel": 1,
                    },
                },
                BEST_MODEL_PATH,
            )

        else:
            no_improvement += 1

        if no_improvement >= PATIENCE:
            print()

            print(
                "Early stopping."
            )

            break

    torch.save(
        {
            "epoch": epoch,
            "model_state_dict": model.state_dict(),
            "optimizer_state_dict": optimizer.state_dict(),
        },
        LAST_MODEL_PATH,
    )

    history_array = np.asarray(
        history_rows,
        dtype=np.float64,
    )

    np.savetxt(
        HISTORY_PATH,
        history_array,
        fmt="%.8f",
        header=(
            "epoch train_loss train_mae train_rmse "
            "val_loss val_mae val_rmse val_corr learning_rate"
        ),
    )

    # --------------------------------------------------------
    # Load best model
    # --------------------------------------------------------

    checkpoint = torch.load(
        BEST_MODEL_PATH,
        map_location=device,
    )

    model.load_state_dict(
        checkpoint[
            "model_state_dict"
        ]
    )

    # --------------------------------------------------------
    # Test
    # --------------------------------------------------------

    test_metrics = run_epoch(
        model,
        test_loader,
        loss_fn,
        device,
        optimizer=None,
    )

    print()

    print(
        "="
        *
        60
    )

    print(
        "Best epoch:",
        best_epoch
    )

    print(
        "Test metrics"
    )

    for key, value in test_metrics.items():
        print(
            f"{key}: {value:.6f}"
        )

    print(
        "="
        *
        60
    )

    with open(
        TEST_METRICS_PATH,
        "w",
        encoding="utf-8",
    ) as f:
        f.write(
            f"best_epoch: {best_epoch}\n"
        )

        for key, value in test_metrics.items():
            f.write(
                f"{key}: {value:.8f}\n"
            )

    # --------------------------------------------------------
    # Predict all original frames
    # --------------------------------------------------------

    raw_frame_count = int(
        frame_ids[-1]
        +
        1
    )

    full_prediction = predict_all_frames(
        model=model,
        normalized_features=normalized_features,
        raw_frame_ids=frame_ids,
        raw_frame_count=raw_frame_count,
        device=device,
    )

    np.savetxt(
        PREDICTION_PATH,
        full_prediction,
        fmt="%.8f",
    )

    print()

    print(
        "Saved model:",
        BEST_MODEL_PATH
    )

    print(
        "Saved normalization:",
        NORMALIZATION_PATH
    )

    print(
        "Saved predictions:",
        PREDICTION_PATH
    )


if __name__ == "__main__":
    main()
